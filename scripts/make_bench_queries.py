#!/usr/bin/env python3
"""Generates bench/queries.txt, the latency workload (IMPLEMENTATION_PLAN problem 1): >= 200
*distinct* queries, so timings measure search rather than a cache.

Deterministic (fixed seed) from ml/data/chunks.json:
  110 plain     3-5 content words from a random slide (stand-ins for natural questions)
   50 filter    module:/week:/type: combined with words
   25 phrase    two consecutive content words from a slide, quoted (sometimes with a filter)
   25 boolean   AND / OR / NOT / groups
When the Phase 4 test questions exist, append them and re-run the planner benchmark.

    python3 scripts/make_bench_queries.py > bench/queries.txt
"""
import json
import os
import random
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SEED = 20261119
STOP = set("""a an and are as at be but by can do does for from has have how if in into is it its of on or
that the their then there these this to was we were what when where which who why will with you your not all
any each more most other some such than too very can just also only use used using one two may i e g s""".split())

rnd = random.Random(SEED)
chunks = json.load(open(os.path.join(ROOT, "ml/data/chunks.json")))["chunks"]
WORD = re.compile(r"[A-Za-z][A-Za-z0-9]{2,}")


def content_words(text):
    return [w.lower() for w in WORD.findall(text) if w.lower() not in STOP]


usable = [c for c in chunks if len(content_words(c["text"])) >= 6]
modules = sorted({c["module"] for c in chunks})
weeks = {m: sorted({c["week"] for c in chunks if c["module"] == m}) for m in modules}
out, seen = [], set()


def add(q):
    if q not in seen:
        seen.add(q)
        out.append(q)
        return 1
    return 0


def words_from(c, n):
    ws = list(dict.fromkeys(content_words(c["text"])))  # unique, in order
    start = rnd.randrange(0, max(1, len(ws) - n))
    return ws[start:start + n]


def phrase_from(c):
    toks = re.findall(r"[A-Za-z][A-Za-z0-9]+", c["text"])
    for _ in range(20):
        i = rnd.randrange(0, max(1, len(toks) - 1))
        a, b = toks[i].lower(), toks[i + 1].lower() if i + 1 < len(toks) else ""
        if b and a not in STOP and b not in STOP and len(a) > 2 and len(b) > 2:
            return f'"{a} {b}"'
    return None


n = 0
while n < 110:
    n += add(" ".join(words_from(rnd.choice(usable), rnd.randint(3, 5))))
n = 0
while n < 50:
    c = rnd.choice(usable)
    ws = " ".join(words_from(c, rnd.randint(1, 3)))
    form = rnd.randrange(4)
    if form == 0:
        q = f"module:{c['module']} {ws}"
    elif form == 1:
        lo = rnd.choice(weeks[c["module"]])
        hi = rnd.choice([w for w in weeks[c["module"]] if w >= lo])
        q = f"module:{c['module']} week:{lo}..{hi} {ws}"
    elif form == 2:
        q = f"week:{c['week']} {ws}"
    else:
        q = f"type:{c['type'].lower()} module:{c['module'][-5:]} {ws}"
    n += add(q)
n = 0
while n < 25:
    c = rnd.choice(usable)
    p = phrase_from(c)
    if p:
        n += add(p if rnd.random() < 0.6 else f"module:{c['module']} {p}")
n = 0
while n < 25:
    a, b = rnd.sample(usable, 2)
    wa, wb = words_from(a, 2), words_from(b, 2)
    form = rnd.randrange(5)
    if form == 0:
        q = f"{wa[0]} AND {wa[1]}"
    elif form == 1:
        q = f"({wa[0]} OR {wb[0]}) {wa[1]}"
    elif form == 2:
        q = f"{wa[0]} {wa[1]} NOT {wb[0]}"
    elif form == 3:
        q = f"module:{a['module']} NOT {wb[0]}"
    else:
        q = f"{wa[0]} OR {wb[0]} OR {wb[1]}"
    n += add(q)

print("# Latency workload: generated by scripts/make_bench_queries.py (seed %d) from the exported corpus." % SEED)
print("# 110 plain, 50 filter, 25 phrase, 25 boolean. Append the Phase 4 test questions when they exist.")
print("\n".join(out))
